//! The identifier of what `lol!` expands to (ALICE-Law G7)
//!
//! A proc macro is compiled for the host as its own crate and its output reaches the
//! user's binary as source text, so the Rust type does not carry the meaning across:
//! `alice-lol` requires `alice-lol-macro` by a caret range, and any release in that range
//! may do the expansion. Every expansion therefore carries this identifier and asks
//! `alice-lol` to compare it with the one `alice-lol` was released with
//! (`::alice_lol::__expect_macro_id!`); a different identifier is a compile error that
//! names both.
//!
//! The identifier is not typed by hand: the test below expands every input of the probe
//! corpus (`expansion_probes.rs`, one call per keyword of the parser plus the literal and
//! capture forms, generated by `scripts/macro_kinds.py`) and hashes a normalized form of the
//! tokens (kind, spelling and spacing of each token, groups by delimiter), so a change to
//! what any keyword expands to fails the test until this value is re-recorded. The
//! normalized form does not depend on how `TokenStream`'s `Display` lays the tokens out.

/// SHA-256 of the normalized expansions of the probe corpus, lower-case hex
pub const EXPANSION_ID_HEX: &str =
    "82a612c32513fdad4f34f617ce8c69ae541d593e4f04004f7fc9f129c64efa10";

#[cfg(test)]
mod tests {
    use super::EXPANSION_ID_HEX;
    use crate::codegen::codegen;
    use crate::parser::LolInput;
    use proc_macro2::{Delimiter, Spacing, TokenStream, TokenTree};
    use sha2::{Digest, Sha256};

    include!("expansion_probes.rs");

    fn put(out: &mut Vec<u8>, tag: u8, text: &str) {
        out.push(tag);
        out.extend_from_slice(&(text.len() as u64).to_le_bytes());
        out.extend_from_slice(text.as_bytes());
    }

    /// kind, spelling and spacing per token; a group as its delimiter around its contents
    fn normalize(tokens: TokenStream, out: &mut Vec<u8>) {
        for tree in tokens {
            match tree {
                TokenTree::Group(g) => {
                    let open = match g.delimiter() {
                        Delimiter::Parenthesis => b'(',
                        Delimiter::Brace => b'{',
                        Delimiter::Bracket => b'[',
                        Delimiter::None => b'0',
                    };
                    out.extend_from_slice(&[b'G', open]);
                    normalize(g.stream(), out);
                    out.push(b'g');
                }
                TokenTree::Ident(i) => put(out, b'I', &i.to_string()),
                TokenTree::Punct(p) => {
                    let joint = p.spacing() == Spacing::Joint;
                    out.extend_from_slice(&[b'P', u8::from(joint)]);
                    put(out, b'p', &p.as_char().to_string());
                }
                TokenTree::Literal(l) => put(out, b'L', &l.to_string()),
            }
        }
    }

    fn expansion_id() -> (String, usize) {
        let inputs: Vec<&str> = KEYWORD_PROBES
            .iter()
            .map(|(_, input)| *input)
            .chain(EXTRA_PROBES.iter().copied())
            .collect();
        let mut h = Sha256::new();
        h.update(b"alice-lol-macro.expansion");
        for input in &inputs {
            let scene: LolInput = syn::parse_str(input)
                .unwrap_or_else(|e| panic!("probe {input:?} does not parse: {e}"));
            let mut bytes = Vec::new();
            normalize(codegen(&scene.body), &mut bytes);
            put(&mut bytes, b'S', input);
            h.update((bytes.len() as u64).to_le_bytes());
            h.update(&bytes);
        }
        let hex = h.finalize().iter().fold(String::new(), |mut acc, b| {
            use std::fmt::Write as _;
            let _ = write!(acc, "{b:02x}");
            acc
        });
        (hex, inputs.len())
    }

    #[test]
    fn identifier_is_the_digest_of_the_probe_expansions() {
        let (hex, probes) = expansion_id();
        assert!(probes > 0, "no probe expanded");
        assert_eq!(
            hex, EXPANSION_ID_HEX,
            "the expansion of the probe corpus moved ({probes} probes): re-record EXPANSION_ID_HEX \
             here and alice-lol's EXPECTED_MACRO_EXPANSION_ID (and its __expect_macro_id! arm) in \
             the same commit"
        );
    }

    /// the keyword arms of `parse_expr`, read from the parser's source
    fn parser_keywords() -> Vec<String> {
        let src = include_str!("parser.rs");
        let body = &src[src.find("fn parse_expr(").expect("parse_expr in parser.rs")..];
        let body = body
            .find("\n        other =>")
            .map_or(body, |end| &body[..end]);
        body.lines()
            .filter_map(|line| {
                let rest = line.strip_prefix("        \"")?;
                let (kw, tail) = rest.split_once('"')?;
                tail.starts_with(" => {").then(|| kw.to_owned())
            })
            .collect()
    }

    #[test]
    fn every_keyword_of_the_parser_has_a_probe() {
        let mut arms = parser_keywords();
        assert!(!arms.is_empty(), "read 0 keywords from parser.rs");
        let mut probed: Vec<String> = KEYWORD_PROBES
            .iter()
            .map(|(kw, _)| (*kw).to_owned())
            .collect();
        arms.sort();
        probed.sort();
        assert_eq!(
            arms, probed,
            "the probe corpus and the parser's keywords differ: run scripts/macro_kinds.py --write"
        );
    }

    #[test]
    fn a_changed_expansion_moves_the_digest() {
        // the normalized form tells apart what an expansion change looks like
        let mut a = Vec::new();
        let mut b = Vec::new();
        normalize(
            quote::quote!(::alice_lol::SdfNode::Sphere { radius: 3f32 }),
            &mut a,
        );
        normalize(
            quote::quote!(::alice_lol::SdfNode::Sphere { radius: 3f64 }),
            &mut b,
        );
        assert_ne!(a, b);
        let mut c = Vec::new();
        let spaced = ":: alice_lol ::SdfNode :: Sphere { radius : 3f32 }";
        normalize(spaced.parse().unwrap(), &mut c);
        assert_eq!(a, c, "layout of the same tokens must not move the digest");
    }
}
