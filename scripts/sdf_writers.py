#!/usr/bin/env python3
"""alice-lol cannot reach an alice-sdf writer that skips the LOL producer identifier (ALICE-Law G8).

alice-sdf's writers of durable forms (export_*, save_*, write_*, to_bytes) store a mesh, a tree or a
volume without LOL's producer identifier; only their `*_with_stamp` forms store it. alice-lol's own
writers (print_export::node_to_stl and the others) go through those. This keeps every other alice-sdf
writer out of alice-lol in two ways:

  * no public re-export: a `pub use` (also `#[doc(hidden)]`, also inside a private module) whose
    canonical target is such a writer, a module that is an ancestor of one, or a type with one as a
    method, is a finding (read from rustdoc's JSON of alice-lol with every feature)
  * no call in library code: every such writer is a `[[method]]` of scripts/clippy_lib_gate.toml, so
    the library clippy refuses a call to it, a wrapper included; each has a canary form

The writer set has one source: alice-sdf's own count of its writers (scripts/provenance_writers.py
of the sibling checkout at the revision .github/alice-siblings pins). `--write` builds alice-sdf's
rustdoc JSON with the features alice-lol enables, takes every public function or method named as
that script names writers, and joins the two by `<file>::<name>`:

  * on both: a writer (unless it is a `*_with_stamp` form, which stores the producer)
  * only in rustdoc, or only in alice-sdf's count: a finding unless scripts/sdf_writers.toml names it
    under [[outside]] with a kind (`writer`, `not-a-writer`, `not-built`) and a reason; an [[outside]]
    entry that no longer disagrees is stale and a finding too

and writes the result to scripts/sdf_writers.lock (with the alice-sdf revision), the alice-sdf block of
scripts/clippy_lib_gate.toml and the canary forms in scripts/clippy-lib-canary. The default run (CI)
does not build alice-sdf's documentation: it checks that the lock is for the pinned revision and that
alice-sdf's count at that revision is the one the lock recorded, that the clippy entries and canary
forms are exactly the lock's writers, and then reads alice-lol's rustdoc JSON for the re-exports.

Exit 1 on a finding; 2 when it compared nothing (no rustdoc item, no public `use`, no re-export into
alice-sdf, no writer) or cannot read what it needs.

    python3 scripts/sdf_writers.py            check (builds alice-lol's rustdoc JSON)
    python3 scripts/sdf_writers.py --write    regenerate the lock, the clippy block and the canary
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "scripts" / "sdf_writers.toml"
LOCK = ROOT / "scripts" / "sdf_writers.lock"
CLIPPY_DATA = ROOT / "scripts" / "clippy_lib_gate.toml"
CANARY_SRC = ROOT / "scripts" / "clippy-lib-canary" / "src" / "lib.rs"
CANARY_TOML = ROOT / "scripts" / "clippy-lib-canary" / "Cargo.toml"
SIBLINGS = ROOT / ".github" / "alice-siblings"
SDF_DIR = ROOT.parent / "ALICE-SDF"
FORMAT_VERSIONS = range(45, 80)
BEGIN, END = "# --- alice-sdf writers (generated by scripts/sdf_writers.py --write) ---", "# --- end alice-sdf writers ---"
RS_BEGIN, RS_END = "// --- alice-sdf writers (generated by scripts/sdf_writers.py --write) ---", "// --- end alice-sdf writers ---"
STAMPED = re.compile(r"_with_stamp$")
KINDS = ("writer", "not-a-writer", "not-built")


# ---------------------------------------------------------------- inputs

def load_config(path: Path = CONFIG) -> dict:
    cfg = tomllib.loads(path.read_text(encoding="utf-8"))
    for e in cfg.get("outside", []):
        if e.get("kind") not in KINDS or not e.get("key") or not str(e.get("reason", "")).strip():
            raise ValueError(f"{path}: an [[outside]] entry needs key, kind ({', '.join(KINDS)}) and a reason: {e}")
    return cfg


def sdf_pin(siblings: Path = SIBLINGS) -> str:
    for line in siblings.read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if parts and parts[0] == "ALICE-SDF" and len(parts) >= 2:
            return parts[1]
    raise ValueError(f"{siblings}: no ALICE-SDF pin")


def sdf_count(sdf_dir: Path = SDF_DIR) -> list[str]:
    """alice-sdf's own writer count: its writers and their variants, as `<file>::<name>`"""
    script = sdf_dir / "scripts" / "provenance_writers.py"
    spec = importlib.util.spec_from_file_location("provenance_writers", script)
    if spec is None or not script.is_file():
        raise ValueError(f"{script}: not found (the alice-sdf sibling checkout)")
    pw = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(pw)
    keys = set(pw.writers(str(sdf_dir))) | {f"{f}::{n}" for f, n in pw.variants(str(sdf_dir))}
    if not keys:
        raise ValueError("alice-sdf's provenance_writers found no writer")
    return sorted(keys)


def sdf_head(sdf_dir: Path = SDF_DIR) -> str:
    p = subprocess.run(["git", "-C", str(sdf_dir), "rev-parse", "HEAD"], capture_output=True, text=True)
    if p.returncode != 0:
        raise ValueError(f"{sdf_dir}: not a git checkout")
    return p.stdout.strip()


def sdf_features() -> list[str]:
    """the features of alice-sdf that alice-lol with every feature turns on (the API alice-lol can reach)"""
    meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--all-features"], cwd=ROOT,
                                     capture_output=True, text=True, check=True).stdout)
    names = {p["id"]: p["name"] for p in meta["packages"]}
    for node in meta["resolve"]["nodes"]:
        if names[node["id"]] == "alice-sdf":
            return sorted(node["features"])
    raise ValueError("cargo metadata resolves no alice-sdf")


def rustdoc(package: str, nightly: str, extra: list[str], manifest: Path = ROOT / "Cargo.toml") -> dict:
    cmd = ["cargo", f"+{nightly}", "rustdoc", "-q", "--manifest-path", str(manifest), "-p", package, "--lib", *extra, "--",
           "-Z", "unstable-options", "--output-format", "json", "--document-hidden-items"]
    if package == "alice-lol":
        cmd.append("--document-private-items")
    p = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    if p.returncode != 0:
        raise ValueError(f"{' '.join(cmd)} failed:\n{p.stderr[-4000:]}")
    meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--no-deps", "--manifest-path",
                                      str(manifest)], cwd=ROOT, capture_output=True, text=True, check=True).stdout)
    doc = json.loads((Path(meta["target_directory"]) / "doc" / f"{package.replace('-', '_')}.json").read_text())
    if doc.get("format_version") not in FORMAT_VERSIONS:
        raise ValueError(f"rustdoc JSON format_version {doc.get('format_version')!r} is not one this check reads")
    return doc


# ---------------------------------------------------------------- alice-sdf's API

def reachable_paths(doc: dict) -> dict[str, list[str]]:
    """item id -> a path a caller outside the crate can write (public modules and public re-exports from the
    crate root; rustdoc's own `paths` entry is where the item is defined, which may be a private module)"""
    out: dict[str, list[str]] = {}
    root = str(doc["root"])
    crate = doc["index"][root]["name"]
    seen = set()
    todo = [(root, [crate])]
    while todo:
        mid, prefix = todo.pop(0)
        if mid in seen:
            continue
        seen.add(mid)
        for child in doc["index"][mid]["inner"]["module"]["items"]:
            item = doc["index"].get(str(child))
            if item is None or item.get("visibility") != "public":
                continue
            inner = item["inner"]
            if "module" in inner:
                out.setdefault(str(child), prefix + [item["name"]])
                todo.append((str(child), prefix + [item["name"]]))
            elif "use" in inner:
                use = inner["use"]
                tid = str(use.get("id"))
                target = doc["index"].get(tid)
                if target is None:
                    continue
                if use.get("is_glob"):
                    if "module" in target["inner"]:
                        todo.append((tid, prefix))
                    continue
                out.setdefault(tid, prefix + [use["name"]])
                if "module" in target["inner"]:
                    todo.append((tid, prefix + [use["name"]]))
            else:
                out.setdefault(str(child), prefix + [item["name"]])
    return out


def method_owners(doc: dict) -> dict[str, str]:
    """item id of an inherent method -> the canonical path of its type"""
    owners = {}
    for item in doc["index"].values():
        im = item["inner"].get("impl")
        if not im or im.get("trait"):
            continue
        rp = (im.get("for") or {}).get("resolved_path")
        if rp:
            for it in im["items"]:
                owners[str(it)] = str(rp["id"])
    return owners


def arg(ty) -> str:
    """an argument expression of the type, for a canary call that only has to type-check"""
    if isinstance(ty, dict):
        if "impl_trait" in ty:
            bounds = json.dumps(ty["impl_trait"])
            if '"AsRef"' in bounds:
                return '"x"'
            if '"Write"' in bounds:
                return "std::io::sink()"
        if "borrowed_ref" in ty and ty["borrowed_ref"].get("is_mutable") and "generic" in ty["borrowed_ref"]["type"]:
            return "&mut std::io::sink()"
        if "generic" in ty:
            return '"x"'
    return "todo!()"


def candidates(doc: dict, name_re: re.Pattern) -> dict[str, dict]:
    """`<file>::<name>` -> {path, canonical, call} for every public function or inherent method named as a
    writer; `path` is a path a caller can write (the clippy entry and the canary call), `canonical` the one
    rustdoc records where the item is defined (how alice-lol's rustdoc names a re-export's target)"""
    owners = method_owners(doc)
    reach = reachable_paths(doc)
    out = {}
    for iid, item in doc["index"].items():
        if item.get("crate_id") != 0 or "function" not in item["inner"] or item.get("visibility") != "public":
            continue
        name = item.get("name") or ""
        if not name_re.fullmatch(name):
            continue
        fname = item["span"]["filename"]
        fname = fname[fname.index("src/"):] if "src/" in fname else fname
        if iid in owners:
            if owners[iid] not in reach:
                continue  # a method of a type no caller can name
            path = [*reach[owners[iid]], name]
            canonical = [*doc["paths"].get(owners[iid], {"path": reach[owners[iid]]})["path"], name]
        elif iid in reach:
            path = reach[iid]
            canonical = doc["paths"].get(iid, {"path": path})["path"]
        else:
            continue  # public but not reachable from the crate root
        inputs = item["inner"]["function"]["sig"]["inputs"]
        args = ", ".join("todo!()" if n == "self" else arg(t) for n, t in inputs)
        out[f"{fname}::{name}"] = {"path": "::".join(path), "canonical": "::".join(canonical),
                                   "call": f"{'::'.join(path)}({args})"}
    return out


def classify(cands: dict[str, dict], count: list[str], outside: list[dict]) -> tuple[list[dict], list[str]]:
    """(writers [{key, path, call}], findings) from the two sources and the [[outside]] entries"""
    found: list[str] = []
    count_set = set(count)
    by_key = {e["key"]: e for e in outside}
    writers = []
    for key in sorted(set(cands) | count_set):
        in_doc, in_count = key in cands, key in count_set
        e = by_key.get(key)
        if in_doc and in_count:
            if e:
                found.append(f"[[outside]] {key}: alice-sdf counts it and its API has it; the entry is stale")
            kind = "writer"
        elif e is None:
            found.append(f"{key}: {'in alice-sdf API but not in its writer count' if in_doc else 'counted by alice-sdf but not in its API with alice-lol features'}; classify it under [[outside]]")
            continue
        else:
            kind = e["kind"]
            if in_doc and kind == "not-built":
                found.append(f"[[outside]] {key}: kind not-built, but alice-sdf's API has it now")
            if not in_doc and kind != "not-built":
                found.append(f"[[outside]] {key}: kind {kind}, but it is not in alice-sdf's API with alice-lol features")
        if kind == "writer" and in_doc and not STAMPED.search(key):
            writers.append({"key": key, **cands[key]})
    for key in by_key:
        if key not in cands and key not in count_set:
            found.append(f"[[outside]] {key}: names nothing in alice-sdf")
    return writers, found


# ---------------------------------------------------------------- generated files

def toml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def render_lock(pin: str, feats: list[str], count: list[str], writers: list[dict]) -> str:
    lines = ["# generated by scripts/sdf_writers.py --write; do not edit",
             f"sdf-revision = {toml_str(pin)}", f"sdf-features = {json.dumps(feats)}", "sdf-count = ["]
    lines += [f"    {toml_str(k)}," for k in count]
    lines.append("]")
    for w in writers:
        lines += ["", "[[writer]]", f"key = {toml_str(w['key'])}", f"path = {toml_str(w['path'])}",
                  f"canonical = {toml_str(w['canonical'])}", f"call = {toml_str(w['call'])}"]
    return "\n".join(lines) + "\n"


def render_clippy_block(writers: list[dict]) -> str:
    out = [BEGIN]
    for w in writers:
        out += ["[[method]]", f"path = {toml_str(w['path'])}",
                'reason = "an alice-sdf writer without the LOL producer identifier (ALICE-Law G8); use print_export / roblox_export"',
                ""]
    for w in writers:
        out += ["[[form]]", f"text = {toml_str(w['call'])}", f"path = {toml_str(w['path'])}", ""]
    out.append(END)
    return "\n".join(out)


def render_canary_block(writers: list[dict]) -> str:
    out = [RS_BEGIN, "// one call of each alice-sdf writer the library may not call; the arguments only type-check",
           "#[allow(unreachable_code, unused_must_use, clippy::diverging_sub_expression)]",
           "pub fn sdf_writers() {"]
    out += [f"    let _ = {w['call']};" for w in writers]
    out += ["}", RS_END]
    return "\n".join(out)


def splice(text: str, begin: str, end: str, block: str, where: str) -> str:
    if begin in text:
        i, j = text.index(begin), text.index(end) + len(end)
        return text[:i] + block + text[j:]
    return text.rstrip("\n") + "\n\n" + block + "\n" if where == "end" else text


def block_of(text: str, begin: str, end: str) -> str | None:
    if begin not in text or end not in text:
        return None
    return text[text.index(begin):text.index(end) + len(end)]


# ---------------------------------------------------------------- alice-lol's re-exports

def reexports(doc: dict, writers: list[dict]) -> tuple[list[str], int, int]:
    """(findings, public use items read, re-exports into alice_sdf)"""
    crates = {cid: c["name"] for cid, c in doc["external_crates"].items()}
    wpaths = [w["canonical"].split("::") for w in writers]
    owners = {tuple(p[:-1]) for p in wpaths}
    out, read, into = [], 0, 0
    for item in doc["index"].values():
        if item.get("crate_id") != 0 or item.get("visibility") != "public" or "use" not in item["inner"]:
            continue
        use = item["inner"]["use"]
        read += 1
        target = doc["paths"].get(str(use.get("id"))) if use.get("id") is not None else None
        if target is None or crates.get(str(target["crate_id"])) != "alice_sdf":
            continue
        into += 1
        path, kind = target["path"], target["kind"]
        where = f"{item['span']['filename']}:{item['span']['begin'][0]}" if item.get("span") else "?"
        shown = f"pub use {use['source']}{'::*' if use.get('is_glob') else ''}"
        joined = "::".join(path)
        if kind == "function" and path in wpaths:
            out.append(f"{where}: {shown} re-exports the writer {joined}")
        elif kind == "module" and any(p[:len(path)] == path for p in wpaths):
            out.append(f"{where}: {shown} re-exports the module {joined}, which holds a writer")
        elif kind in ("struct", "enum", "union", "trait") and tuple(path) in owners:
            out.append(f"{where}: {shown} re-exports {joined}, which has a writer method")
    return out, read, into


# ---------------------------------------------------------------- modes

def generate(cfg: dict) -> tuple[list[str], int]:
    pin, head = sdf_pin(), sdf_head()
    if pin != head:
        raise ValueError(f"the alice-sdf checkout is at {head[:12]}, .github/alice-siblings pins {pin[:12]}")
    count = sdf_count()
    feats = sdf_features()
    # the canary crate takes alice-sdf with exactly these features, and alice-sdf's documentation is built
    # through it, so the API read here is the API the canary calls
    toml = CANARY_TOML.read_text(encoding="utf-8")
    dep = (f'alice-sdf = {{ path = "../../../ALICE-SDF", default-features = false, features = {json.dumps(feats)} }}'
           "  # generated by scripts/sdf_writers.py --write")
    toml = re.sub(r"(?m)^alice-sdf = .*$", dep, toml) if re.search(r"(?m)^alice-sdf = ", toml) else toml.rstrip("\n") + "\n" + dep + "\n"
    CANARY_TOML.write_text(toml, encoding="utf-8")
    doc = rustdoc("alice-sdf", cfg["nightly"], [], CANARY_TOML)
    cands = candidates(doc, re.compile(cfg["name"]))
    writers, found = classify(cands, count, cfg.get("outside", []))
    if found:
        return found, len(writers)
    LOCK.write_text(render_lock(pin, feats, count, writers), encoding="utf-8")
    data = CLIPPY_DATA.read_text(encoding="utf-8")
    CLIPPY_DATA.write_text(splice(data, BEGIN, END, render_clippy_block(writers), "end"), encoding="utf-8")
    src = CANARY_SRC.read_text(encoding="utf-8")
    CANARY_SRC.write_text(splice(src, RS_BEGIN, RS_END, render_canary_block(writers), "end"), encoding="utf-8")
    return [], len(writers)


def check_lock(cfg: dict, lock: dict, count: list[str], pin: str, clippy_text: str, canary_text: str) -> list[str]:
    found = []
    if lock.get("sdf-revision") != pin:
        found.append(f"scripts/sdf_writers.lock is for alice-sdf {str(lock.get('sdf-revision'))[:12]}, "
                     f".github/alice-siblings pins {pin[:12]}: run scripts/sdf_writers.py --write")
    if lock.get("sdf-features") != sdf_features():
        found.append(f"alice-lol now turns on alice-sdf features {sdf_features()}, the lock was built with "
                     f"{lock.get('sdf-features')}: run --write")
    if lock.get("sdf-count") != count:
        added = sorted(set(count) - set(lock.get("sdf-count", [])))
        gone = sorted(set(lock.get("sdf-count", [])) - set(count))
        found.append(f"alice-sdf's writer count differs from the lock (new {added}, gone {gone}): run --write")
    writers = lock.get("writer", [])
    if block_of(clippy_text, BEGIN, END) != render_clippy_block(writers):
        found.append("scripts/clippy_lib_gate.toml: the alice-sdf block is not the lock's writers: run --write")
    if block_of(canary_text, RS_BEGIN, RS_END) != render_canary_block(writers):
        found.append("scripts/clippy-lib-canary/src/lib.rs: the alice-sdf block is not the lock's writers: run --write")
    return found


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--lol-json", type=Path, help="alice-lol's rustdoc JSON instead of building it (the tests)")
    a = ap.parse_args(argv)
    try:
        cfg = load_config()
        if a.write:
            found, n = generate(cfg)
            for f in found:
                print(f"error: {f}", file=sys.stderr)
            print(f"sdf-writers --write: {n} writer(s), {len(found)} finding(s)")
            if n == 0:
                print("sdf-writers: no writer (compared nothing)", file=sys.stderr)
                return 2
            return 1 if found else 0
        lock = tomllib.loads(LOCK.read_text(encoding="utf-8"))
        found = check_lock(cfg, lock, sdf_count(), sdf_pin(), CLIPPY_DATA.read_text(encoding="utf-8"),
                           CANARY_SRC.read_text(encoding="utf-8"))
        doc = json.loads(a.lol_json.read_text()) if a.lol_json else rustdoc("alice-lol", cfg["nightly"], ["--all-features"])
        more, read, into = reexports(doc, lock.get("writer", []))
        found += more
    except (OSError, ValueError, KeyError, json.JSONDecodeError, tomllib.TOMLDecodeError) as e:
        print(f"sdf-writers: {e}", file=sys.stderr)
        return 2
    for f in found:
        print(f"error: {f}", file=sys.stderr)
    n = len(lock.get("writer", []))
    print(f"sdf-writers: {n} alice-sdf writer(s), {read} public use item(s), {into} into alice_sdf, {len(found)} finding(s)")
    if n == 0 or read == 0 or into == 0:
        print("sdf-writers: compared nothing (no writer, no public use item, or none into alice_sdf)", file=sys.stderr)
        return 2
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
