#!/usr/bin/env bash
# The packaged `alice-lol`, built the way a user gets it: its dependencies from crates.io.
#
# Inside this workspace every sibling crate (`alice-sdf`, `alice-zip`, ...) is a path to a
# checkout of its main branch, so the build never sees the versions a published
# `alice-lol` resolves to. This script packages `alice-lol-macro` and `alice-lol`, puts the
# packaged `alice-lol` into a throwaway crate (the packaged manifest has no paths: every
# dependency is its version requirement on crates.io), and compiles there:
#   - `alice-lol/tests/macro_every_kind.rs` (every keyword of the macro, generated by
#     `scripts/macro_kinds.py`), so an emitted constructor that does not match the published
#     `alice-sdf` fails to compile;
#   - the lock of that build has one version of each `alice-*` crate.
# The macro is taken from its package (a `[patch]`), because `alice-lol` requires the
# version this workspace is about to publish; that the published macro is the same source
# as the local one is `scripts/published_source_check.py`.
#
# It also rebuilds the same packaged crate from an isolated copy with no Cargo.lock
# reachable by any ancestor walk from its own extracted directory: a real crates.io
# consumer's project root and wherever cargo extracts the dependency are unrelated
# subtrees, so anything alice-lol's own build does must not assume a nearby Cargo.lock
# exists at all.
#
# A sibling version this commit requires that crates.io does not have yet (an `alice-sdf`
# release still to be published) cannot resolve from crates.io. `scripts/package_integrity.py`
# (shared with the other ALICE crates) decides which dependencies are blocked that way and
# prints one `--config=patch.crates-io.<name>.path=...` per blocked dependency; every cargo
# command below takes exactly that set, it is written to `$OUT/patches.txt` (CI compares it
# with a fresh run of the tool), and a blocked crate is the only one allowed to come from a
# path in the consumer's lock. A dependency that is not blocked still has to come from
# crates.io, and any other failure stays a failure.
#
# usage: scripts/registry_consumer.sh
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT=${REGISTRY_CONSUMER_DIR:-$ROOT/target/registry-consumer}
rm -rf "$OUT"
mkdir -p "$OUT/pkg" "$OUT/tests"

cd "$ROOT"
python3 scripts/macro_kinds.py --check
# the blocked dependencies (stdout: one --config per blocked dependency; a finding exits 1)
PATCH_OUT=$(python3 scripts/package_integrity.py --member alice-lol --patches)
PATCHES=()
BLOCKED=()
while IFS= read -r line; do
  [ -n "$line" ] || continue
  case "$line" in
    --config=patch.crates-io.*.path=*) ;;
    *) echo "error: unexpected line from package_integrity.py --patches: $line" >&2; exit 1 ;;
  esac
  PATCHES+=("$line")
  name=${line#--config=patch.crates-io.}
  BLOCKED+=("${name%%.path=*}")
done <<< "$PATCH_OUT"
: > "$OUT/patches.txt"
for line in ${PATCHES[@]+"${PATCHES[@]}"}; do printf '%s\n' "$line" >> "$OUT/patches.txt"; done
echo "registry consumer: ${#PATCHES[@]} blocked dependency patch(es)${BLOCKED[*]+: ${BLOCKED[*]}}"
is_blocked() { local b; for b in ${BLOCKED[@]+"${BLOCKED[@]}"}; do [ "$b" = "$1" ] && return 0; done; return 1; }
cargo package -q -p alice-lol-macro -p alice-lol --no-verify ${REGISTRY_CONSUMER_ALLOW_DIRTY:+--allow-dirty} ${PATCHES[@]+"${PATCHES[@]}"}
version() { sed -n 's/^version = "\(.*\)"/\1/p' "$1" | head -1; }
LOL=$(version alice-lol/Cargo.toml)
MACRO=$(version alice-lol-macro/Cargo.toml)
for c in "alice-lol-$LOL" "alice-lol-macro-$MACRO"; do
  # -m: the package stores one fixed mtime for every file, so a reused build directory
  # would not see a changed source; extract with the current time instead
  tar -xmzf "target/package/$c.crate" -C "$OUT/pkg"
done
if awk '/^\[/{dep=($0 ~ /dependencies/)} dep && /^path *=/' "$OUT/pkg/alice-lol-$LOL/Cargo.toml" | grep .; then
  echo "error: the packaged alice-lol manifest still has a path dependency" >&2
  exit 1
fi

cat > "$OUT/Cargo.toml" <<EOF
[package]
name = "lol-registry-consumer"
version = "0.0.0"
edition = "2021"
publish = false

[dependencies]
alice-lol = { path = "pkg/alice-lol-$LOL" }

[patch.crates-io]
alice-lol-macro = { path = "pkg/alice-lol-macro-$MACRO" }

[workspace]
EOF
mkdir -p "$OUT/src"
echo "" > "$OUT/src/lib.rs"
cp alice-lol/tests/macro_every_kind.rs "$OUT/tests/"

LOG="$OUT/test.log"
CARGO_TARGET_DIR="${REGISTRY_CONSUMER_TARGET:-$ROOT/target/registry-consumer-target}" cargo ${PATCHES[@]+"${PATCHES[@]}"} test --manifest-path "$OUT/Cargo.toml" --test macro_every_kind 2>&1 | tee "$LOG"

# the build used the packaged macro and crates.io for the siblings
lock="$OUT/Cargo.lock"
# the [[package]] entry of a crate (not a [[patch.unused]] entry: a patch cargo did not use
# is listed there by name and must not read as linked)
block() { awk -v n="$1" '/^\[/{pkg=($0=="[[package]]"); p=0} pkg && $0=="name = \""n"\""{p=1} p' "$lock"; }
if block alice-lol-macro | grep '^source' >/dev/null; then
  echo "error: the [patch] for alice-lol-macro was not used (alice-lol requires another version)" >&2
  exit 1
fi
for c in alice-sdf alice-det-math; do
  if is_blocked "$c"; then
    if block "$c" | grep '^source' >/dev/null; then
      echo "error: $c is blocked (unpublished) but the consumer's lock took it from a registry, not the patch" >&2
      exit 1
    fi
    echo "registry consumer: $c from its sibling (blocked: unpublished on crates.io)"
  elif ! block "$c" | grep '^source = "registry+' >/dev/null; then
    echo "error: $c is not from crates.io in the consumer's lock" >&2
    exit 1
  fi
done
for b in ${BLOCKED[@]+"${BLOCKED[@]}"}; do
  if [ -z "$(block "$b")" ]; then
    echo "error: $b is blocked (unpublished) but is not in the consumer's lock at all" >&2
    exit 1
  fi
  if block "$b" | grep '^source' >/dev/null; then
    echo "error: $b is blocked (unpublished) but the consumer's lock did not use the patch" >&2
    exit 1
  fi
done
grep -q '^test every_keyword_of_the_macro_builds_a_node \.\.\. ok' "$LOG" || {
  echo "error: the every-keyword test did not run" >&2
  exit 1
}
EMPTY=$(mktemp)
python3 scripts/lock_single_version.py --lock "$lock" --baseline "$EMPTY"
rm -f "$EMPTY"

# Regression: a real crates.io consumer's own Cargo.lock is not necessarily
# reachable by walking up from wherever cargo extracts the dependency's
# source — that extracted path and the consumer's project root can be
# unrelated subtrees. `$OUT/pkg/alice-lol-$LOL` above is nested 2 levels
# under `$OUT`'s own Cargo.lock, which does not catch that: a `build.rs`
# that assumed an ancestor Cargo.lock always exists passed there but
# panicked for a real consumer (see the removal of alice-lol/build.rs).
# Rebuild the SAME packaged crate from an unpacked copy that has no
# Cargo.lock anywhere above it, consumed by a throwaway workspace whose own
# Cargo.lock lives in a wholly separate subtree, so an ancestor-walk from
# the packaged crate's own directory cannot reach it either.
ISOLATED=$(mktemp -d)
mkdir -p "$ISOLATED/no-ancestor-lock/pkg"
tar -xmzf "target/package/alice-lol-$LOL.crate" -C "$ISOLATED/no-ancestor-lock/pkg"
tar -xmzf "target/package/alice-lol-macro-$MACRO.crate" -C "$ISOLATED/no-ancestor-lock/pkg"
mkdir -p "$ISOLATED/consumer/src"
cat > "$ISOLATED/consumer/Cargo.toml" <<EOF
[package]
name = "lol-no-ancestor-lock-consumer"
version = "0.0.0"
edition = "2021"
publish = false

[dependencies]
alice-lol = { path = "$ISOLATED/no-ancestor-lock/pkg/alice-lol-$LOL" }

[patch.crates-io]
alice-lol-macro = { path = "$ISOLATED/no-ancestor-lock/pkg/alice-lol-macro-$MACRO" }

[workspace]
EOF
echo "" > "$ISOLATED/consumer/src/lib.rs"
ISO_LOG="$ISOLATED/build.log"
if ! CARGO_TARGET_DIR="$ISOLATED/target" cargo ${PATCHES[@]+"${PATCHES[@]}"} build --manifest-path "$ISOLATED/consumer/Cargo.toml" > "$ISO_LOG" 2>&1; then
  echo "error: alice-lol $LOL failed to build when its own Cargo.lock is not reachable by any ancestor walk (this must succeed for any real crates.io consumer):" >&2
  cat "$ISO_LOG" >&2
  rm -rf "$ISOLATED"
  exit 1
fi
rm -rf "$ISOLATED"
echo "registry consumer: alice-lol $LOL builds with no ancestor Cargo.lock reachable from its own extracted directory"

sdf_version=$(block alice-sdf | sed -n 's/^version = //p' | tr -d '"')
if is_blocked alice-sdf; then
  echo "registry consumer: alice-lol $LOL + alice-lol-macro $MACRO built against crates.io, alice-sdf $sdf_version from its sibling (blocked)"
else
  echo "registry consumer: alice-lol $LOL + alice-lol-macro $MACRO built against crates.io (alice-sdf $sdf_version)"
fi
