#!/usr/bin/env python3
"""Every keyword of the `lol!` macro, compiled through the macro.

The keyword list is read from `alice-lol-macro/src/parser.rs` (the arms of `parse_expr`),
and the arguments of each keyword from the argument readers its arm calls in order
(`parse_2f` = two numbers, `parse_1f_child` = a number and a child, ...). The test file
`alice-lol/tests/macro_every_kind.rs` is generated from that list: one `lol!` call per
keyword, so a node kind whose emitted constructor no longer matches `alice-sdf` fails to
compile. CI compiles the same file against `alice-sdf` from crates.io
(`scripts/registry_consumer.sh`), where the published versions are what a user gets.

The same list, with a few extra forms (the `field` wrapper, a captured expression, a bare
variable and literal edge cases), is written to `alice-lol-macro/src/expansion_probes.rs`:
the probe corpus whose expansions the macro's identifier (`EXPANSION_ID_HEX`) digests, so a
keyword without a probe cannot change its expansion with the identifier unmoved (ALICE-Law G7).

usage: macro_kinds.py --write | --check
Exit 1 when a generated file is not current, 2 when no keyword was read.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PARSER = ROOT / "alice-lol-macro" / "src" / "parser.rs"
TEST = ROOT / "alice-lol" / "tests" / "macro_every_kind.rs"
PROBES = ROOT / "alice-lol-macro" / "src" / "expansion_probes.rs"

# forms beyond one call per keyword: the `field` wrapper, a captured expression and a bare
# variable (numeric positions), and literals whose rounding to f32 is the macro's own work
EXTRA_PROBES = [
    "field Probe { sphere(1.0) }",
    "sphere({r * 2.0})",
    "sphere(r)",
    "sphere(-2.5)",
    "sphere(-0.0)",
    "sphere(0.1)",
    "sphere(7)",
    "sphere(1e-40)",
    "sphere(16777217.000000001)",
]

NUM = "3.0"  # one value for every number: a size, a count of 3, an angle, a smoothing width
CHILD = "sphere(1.0)"
CHILD2 = "box3d(1.0, 1.0, 1.0)"

# a keyword whose numeric arguments are not independent (NUM filled into every
# "n" slot would not satisfy a cross-argument constraint checked_* refuses):
# the literal number tokens to use instead, in argument order (non-numeric
# slots keep using CHILD/CHILD2 from `call` as normal). rotate_q's x/y/z/w
# must be unit length within alice_lol::limits::ROTATION_QUAT_UNIT_TOLERANCE
# -- (0, 0, 0, 1) is the identity quaternion, exactly unit.
NUM_OVERRIDE = {
    "rotate_q": ["0.0", "0.0", "0.0", "1.0"],
}

# argument reader -> what it reads, in order ("n" = a number, "c" = a child expression)
SHAPES = {
    "parse_val": "n",
    "parse_expr": "c",
    "parse_child_only": "c",
    "parse_children": "cc",
    "parse_k_children": "ncc",
    "parse_2f_children": "nncc",
    "parse_1f_ab": "ncc",
    "parse_2f_ab": "nncc",
}


def shape_of(reader: str) -> str:
    if reader in SHAPES:
        return SHAPES[reader]
    m = re.fullmatch(r"parse_(\d+)f(_child)?", reader)
    if not m:
        raise SystemExit(f"error: unknown argument reader {reader}")
    return "n" * int(m.group(1)) + ("c" if m.group(2) else "")


def keywords() -> list[tuple[str, str]]:
    src = PARSER.read_text(encoding="utf-8")
    body = src[src.index("fn parse_expr(") :]
    body = body[: body.index("\n        other =>")] if "\n        other =>" in body else body
    parts = re.split(r'\n        "([a-z_0-9]+)" => \{', body)
    out = []
    for k in range(1, len(parts), 2):
        readers = re.findall(r"\b(parse_[a-z0-9_]+)\(&content\)", parts[k + 1])
        if not readers:
            raise SystemExit(f"error: keyword {parts[k]} calls no argument reader")
        out.append((parts[k], "".join(shape_of(r) for r in readers)))
    return out


def call(kw: str, shape: str) -> str:
    children = iter([CHILD, CHILD2, CHILD, CHILD2])
    nums = iter(NUM_OVERRIDE.get(kw, []))
    args = [(next(nums, NUM) if a == "n" else next(children)) for a in shape]
    return f"{kw}({', '.join(args)})"


def render(kws: list[tuple[str, str]]) -> str:
    lines = [
        "//! Every keyword of the `lol!` macro, compiled through the macro",
        "//!",
        "//! Generated by `scripts/macro_kinds.py --write` from the keyword arms of",
        "//! `alice-lol-macro/src/parser.rs` (do not edit) A node kind whose emitted",
        "//! constructor does not match `alice-sdf` fails to compile here CI also compiles",
        "//! this file against `alice-sdf` from crates.io (`scripts/registry_consumer.sh`)",
        "",
        "use alice_lol::{lol, SdfNode};",
        "",
        "/// the number of keywords in the macro's parser",
        f"const KEYWORDS: usize = {len(kws)};",
        "const _: () = assert!(KEYWORDS > 0, \"no keyword compiled\");",
        "",
        "#[rustfmt::skip]",
        "#[allow(clippy::too_many_lines, reason = \"one line per keyword of the macro's parser\")]",
        "fn every_kind() -> Vec<(&'static str, SdfNode)> {",
        "    vec![",
    ]
    lines += [f'        ("{kw}", lol! {{ {call(kw, shape)} }}),' for kw, shape in kws]
    lines += [
        "    ]",
        "}",
        "",
        "#[test]",
        "fn every_keyword_of_the_macro_builds_a_node() {",
        "    let kinds = every_kind();",
        "    assert_eq!(kinds.len(), KEYWORDS);",
        "    let mut names: Vec<&str> = kinds.iter().map(|(k, _)| *k).collect();",
        "    names.sort_unstable();",
        "    names.dedup();",
        "    assert_eq!(names.len(), KEYWORDS, \"a keyword is listed twice\");",
        "    for (kw, node) in &kinds {",
        "        assert!(node.node_count() > 0, \"{kw}: empty node\");",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def render_probes(kws: list[tuple[str, str]]) -> str:
    lines = [
        "// The probe corpus of the macro's identifier (`EXPANSION_ID_HEX`), included into the test",
        "// module of `expansion_id.rs`",
        "//",
        "// Generated by `scripts/macro_kinds.py --write` from the keyword arms of `parser.rs`",
        "// (do not edit) one call per keyword, then the forms in `EXTRA_PROBES`",
        "",
        "/// `(keyword, input)` per keyword of `parse_expr`, in the parser's order",
        "#[rustfmt::skip]",
        "const KEYWORD_PROBES: &[(&str, &str)] = &[",
    ]
    lines += [f'    ("{kw}", "{call(kw, shape)}"),' for kw, shape in kws]
    lines += [
        "];",
        "",
        "/// inputs beyond one call per keyword",
        "#[rustfmt::skip]",
        "const EXTRA_PROBES: &[&str] = &[",
    ]
    lines += [f'    "{p}",' for p in EXTRA_PROBES]
    lines += ["];", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if argv not in (["--write"], ["--check"]):
        print(__doc__.strip().splitlines()[-2], file=sys.stderr)
        return 2
    kws = keywords()
    if not kws:
        print("error: read 0 keywords from the macro's parser", file=sys.stderr)
        return 2
    files = [(TEST, render(kws)), (PROBES, render_probes(kws))]
    if argv == ["--write"]:
        for path, text in files:
            path.write_text(text, encoding="utf-8", newline="\n")
        print(f"macro kinds: wrote {len(kws)} keywords to {len(files)} files")
        return 0
    stale = [path for path, text in files
             if (path.read_text(encoding="utf-8") if path.exists() else "") != text]
    for path in stale:
        print(f"error: {path.relative_to(ROOT)} is not the generated file for the {len(kws)} keywords "
              "of the macro's parser; run scripts/macro_kinds.py --write", file=sys.stderr)
    if stale:
        return 1
    print(f"macro kinds: compared {len(kws)} keywords, {len(files)} files are current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
