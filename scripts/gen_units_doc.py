#!/usr/bin/env python3
"""Write the units paragraph of the documents from the language definition

source:    the `unit` table and `purpose` list of alice-lol/language/constructs.toml
generated: the text between the lines `<!-- units:begin -->` and `<!-- units:end -->` in every
           tracked `*.md` that has the markers, each on a line of its own (found with `git ls-files`, so a new document is covered
           by adding the markers)

usage: python3 scripts/gen_units_doc.py           write the generated blocks
       python3 scripts/gen_units_doc.py --check   compare instead (exit 1 on a difference)

Either mode fails when no document has the markers, when a document has a begin marker without
its end (or the markers twice), or when the definition has no unit rows or no purposes
"""
from __future__ import annotations

import re
import subprocess
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from utf8_stdio import fix_encoding  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DEFINITION = ROOT / "alice-lol" / "language" / "constructs.toml"
BEGIN = "<!-- units:begin -->"
END = "<!-- units:end -->"
# a marker counts only on a line of its own (a document may mention the markers in prose)
BEGIN_LINE = re.compile(r"^" + re.escape(BEGIN) + r"$", re.M)
END_LINE = re.compile(r"^" + re.escape(END) + r"$", re.M)


class DefinitionError(Exception):
    """the definition or a document's markers cannot be used"""


def fmt_mm(mm: float) -> str:
    return f"{mm:g} mm"


def render(definition: dict) -> str:
    units = definition.get("unit", [])
    purposes = definition.get("purpose", [])
    if not units or not purposes:
        raise DefinitionError("the definition has no unit rows or no purposes")
    rows = "\n".join(
        f"| `{u['name']}` | {fmt_mm(u['mm']) if 'mm' in u else 'no physical size'} | "
        f"{', '.join(f'`{p}`' for p in purposes) if 'mm' in u else '`render` only'} |"
        for u in units)
    length = next(u["name"] for u in units if "mm" in u)
    plain = next((u["name"] for u in units if "mm" not in u), None)
    render_line = (f"; a scene with no physical size is `units({plain}, render, <program>)`"
                   if plain else "")
    return f"""{BEGIN}
<!-- generated by scripts/gen_units_doc.py from alice-lol/language/constructs.toml; do not edit -->
**Units.** A program says what its numbers are with one declaration at the root (never nested):
`units(<unit>, <purpose>, <program>)`, for example `units({length}, print, cylinder(50, 5))`{render_line}.
Every length argument is in the declared unit; angles stay in degrees.

| unit | one program unit | purposes |
|------|------------------|----------|
{rows}

Exported with a declaration, the scale is the unit and the bounds are the shape's own tight box
(no fixed scene box, nothing is cut off). A program without a declaration is exported with the
`PrintConfig` scale and bounds of the caller and gets the warning `LOL-U001`.
{END}"""


def documents() -> list[Path]:
    tracked = subprocess.run(["git", "-C", str(ROOT), "ls-files", "-z", "--", "*.md"],
                             capture_output=True, text=True, check=True).stdout.split("\0")
    return sorted(ROOT / p for p in tracked
                  if p and BEGIN_LINE.search((ROOT / p).read_text(encoding="utf-8")))


def replace(text: str, block: str, where: str) -> str:
    begins, ends = list(BEGIN_LINE.finditer(text)), list(END_LINE.finditer(text))
    if len(begins) != 1 or len(ends) != 1 or begins[0].start() > ends[0].start():
        raise DefinitionError(f"{where}: needs exactly one {BEGIN} line followed by one {END} line")
    return text[:begins[0].start()] + block + text[ends[0].end():]


def main(argv: list[str]) -> int:
    fix_encoding()
    check = "--check" in argv[1:]
    try:
        with DEFINITION.open("rb") as f:
            block = render(tomllib.load(f))
        docs = documents()
        if not docs:
            raise DefinitionError(f"no tracked document has {BEGIN}")
        stale = []
        for path in docs:
            rel = path.relative_to(ROOT)
            text = path.read_text(encoding="utf-8")
            new = replace(text, block, str(rel))
            if new == text:
                continue
            if check:
                stale.append(str(rel))
            else:
                path.write_text(new, encoding="utf-8")
                print(f"wrote {rel}")
    except DefinitionError as e:
        print(f"gen_units_doc: {e}", file=sys.stderr)
        return 1
    if stale:
        print(f"gen_units_doc: not generated from the definition: {stale}"
              " (run python3 scripts/gen_units_doc.py)", file=sys.stderr)
        return 1
    print(f"gen_units_doc: {len(docs)} documents {'match' if check else 'up to date'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
